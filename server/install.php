<?php
/**
 * One-time installer: writes config.php, creates tables and the first admin.
 * Refuses to run once config.php exists.
 */

declare(strict_types=1);

define('RISHE_INSTALLING', true);
require __DIR__ . '/core/bootstrap.php';

header('Content-Type: text/html; charset=utf-8');
header('X-Frame-Options: DENY');

$installed = is_file(RISHE_ROOT . '/config.php');
$errors    = [];
$done      = false;

$https    = !empty($_SERVER['HTTPS']) && $_SERVER['HTTPS'] !== 'off';
$host     = preg_replace('/[^A-Za-z0-9.\-:]/', '', (string) ($_SERVER['HTTP_HOST'] ?? 'localhost'));
$dir      = rtrim(str_replace('\\', '/', dirname((string) ($_SERVER['SCRIPT_NAME'] ?? '/install.php'))), '/');
$guess    = ($https ? 'https' : 'http') . '://' . $host . $dir;

$v = [
	'db_host'     => 'localhost',
	'db_port'     => '3306',
	'db_name'     => '',
	'db_user'     => '',
	'base_url'    => $guess,
	'admin_name'  => '',
	'admin_email' => '',
	'sample'      => '1',
];

if (!$installed && strtoupper((string) ($_SERVER['REQUEST_METHOD'] ?? '')) === 'POST') {
	foreach ($v as $key => $default) {
		$v[$key] = rishe_str($_POST, $key, 255);
	}
	$db_pass    = isset($_POST['db_pass']) && is_string($_POST['db_pass']) ? $_POST['db_pass'] : '';
	$admin_pass = isset($_POST['admin_pass']) && is_string($_POST['admin_pass']) ? $_POST['admin_pass'] : '';
	$v['base_url'] = rtrim($v['base_url'], '/');

	if ($v['db_name'] === '' || $v['db_user'] === '') {
		$errors[] = 'نام دیتابیس و نام کاربری دیتابیس را وارد کنید.';
	}
	if (!filter_var($v['base_url'], FILTER_VALIDATE_URL)) {
		$errors[] = 'آدرس نصب معتبر نیست.';
	}
	if ($v['admin_name'] === '' || !filter_var($v['admin_email'], FILTER_VALIDATE_EMAIL)) {
		$errors[] = 'نام و ایمیل معتبر برای مدیر وارد کنید.';
	}
	if (mb_strlen($admin_pass) < 8) {
		$errors[] = 'رمز مدیر باید حداقل ۸ کاراکتر باشد.';
	}
	if (!is_writable(RISHE_ROOT)) {
		$errors[] = 'پوشه‌ی برنامه قابل نوشتن نیست؛ دسترسی را درست کنید یا config.php را دستی از روی config.sample.php بسازید.';
	}

	if (!$errors) {
		$config = [
			'db'       => ['host' => $v['db_host'], 'port' => (int) $v['db_port'], 'name' => $v['db_name'], 'user' => $v['db_user'], 'pass' => $db_pass],
			'base_url' => $v['base_url'],
			'app_key'  => bin2hex(random_bytes(32)),
			'debug'    => false,
		];
		try {
			$pdo = Rishe_DB::connect($config['db']);
			$schema = preg_replace('/^\s*--.*$/m', '', (string) file_get_contents(RISHE_ROOT . '/database/schema.sql')) ?? '';
			foreach (array_filter(array_map('trim', explode(';', $schema))) as $sql) {
				$pdo->exec($sql);
			}
			Rishe_Config::load($config);

			if (Rishe_DB::value('SELECT COUNT(*) FROM rishe_admins')) {
				throw new RuntimeException('این دیتابیس قبلاً نصب شده است (مدیر وجود دارد).');
			}
			Rishe_DB::insert('rishe_admins', [
				'name'          => $v['admin_name'],
				'email'         => mb_strtolower($v['admin_email']),
				'password_hash' => password_hash($admin_pass, PASSWORD_DEFAULT),
				'created_at'    => rishe_now(),
			]);
			if ($v['sample'] === '1' && !Rishe_DB::value('SELECT COUNT(*) FROM rishe_courses')) {
				(require RISHE_ROOT . '/database/sample.php')();
			}

			$php = "<?php\n// Generated by install.php\nreturn " . var_export($config, true) . ";\n";
			if (file_put_contents(RISHE_ROOT . '/config.php', $php, LOCK_EX) === false) {
				throw new RuntimeException('ساخت config.php انجام نشد.');
			}
			@chmod(RISHE_ROOT . '/config.php', 0640);
			$done = true;
		} catch (PDOException $e) {
			$errors[] = 'اتصال یا ساخت جدول‌ها انجام نشد: ' . $e->getMessage();
		} catch (RuntimeException $e) {
			$errors[] = $e->getMessage();
		}
	}
}
?>
<!doctype html>
<html lang="fa" dir="rtl">
<head>
	<meta charset="utf-8">
	<meta name="viewport" content="width=device-width, initial-scale=1">
	<meta name="robots" content="noindex">
	<title>نصب ریشه</title>
	<link rel="stylesheet" href="assets/admin.css">
</head>
<body class="rishe-auth">
	<div class="rishe-auth-card" style="max-width:560px">
		<div class="rishe-brand"><span class="rishe-brand-mark"><svg class="rishe-icon" viewBox="0 0 24 24"><path d="M12 3v8M12 11c0 4-4 4-4 8M12 11c0 4 4 4 4 8M12 11v10"/></svg></span><span><b>نصب ریشه</b><small>پنل مدیریت و API اپ</small></span></div>

		<?php if ($done) : ?>
			<div class="rishe-flash is-ok">نصب کامل شد.</div>
			<p>برای امنیت، همین حالا فایل <b class="ltr">install.php</b> را از هاست حذف کنید.</p>
			<p class="rishe-help">آدرس API برای اپ: <span class="ltr"><?php echo rishe_e(rishe_url('api/v1/')); ?></span></p>
			<a class="rishe-btn is-primary is-block" href="admin/">ورود به پنل مدیریت</a>
		<?php elseif ($installed) : ?>
			<div class="rishe-flash is-warn">برنامه قبلاً نصب شده است. این فایل را از هاست حذف کنید.</div>
			<a class="rishe-btn is-block" href="admin/">رفتن به پنل</a>
		<?php else : ?>
			<?php foreach ($errors as $error) : ?><div class="rishe-flash is-bad"><?php echo rishe_e($error); ?></div><?php endforeach; ?>
			<form method="post" class="rishe-form" autocomplete="off">
				<h2 style="margin:0;font-size:15px">دیتابیس MySQL</h2>
				<div class="rishe-grid is-2">
					<label class="rishe-field"><span>میزبان</span><input class="rishe-input ltr" name="db_host" id="db_host" value="<?php echo rishe_e($v['db_host']); ?>"></label>
					<label class="rishe-field"><span>پورت</span><input class="rishe-input ltr" name="db_port" id="db_port" value="<?php echo rishe_e($v['db_port']); ?>"></label>
					<label class="rishe-field"><span>نام دیتابیس</span><input class="rishe-input ltr" name="db_name" id="db_name" required value="<?php echo rishe_e($v['db_name']); ?>"></label>
					<label class="rishe-field"><span>نام کاربری</span><input class="rishe-input ltr" name="db_user" id="db_user" required value="<?php echo rishe_e($v['db_user']); ?>"></label>
				</div>
				<label class="rishe-field"><span>رمز دیتابیس</span><input class="rishe-input ltr" type="password" name="db_pass" id="db_pass"></label>
				<label class="rishe-field"><span>آدرس نصب</span><input class="rishe-input ltr" name="base_url" id="base_url" value="<?php echo rishe_e($v['base_url']); ?>"><small>آدرس همین پوشه روی سایت، ترجیحاً با https</small></label>

				<h2 style="margin:8px 0 0;font-size:15px">مدیر پنل</h2>
				<div class="rishe-grid is-2">
					<label class="rishe-field"><span>نام</span><input class="rishe-input" name="admin_name" id="admin_name" required value="<?php echo rishe_e($v['admin_name']); ?>"></label>
					<label class="rishe-field"><span>ایمیل</span><input class="rishe-input ltr" type="email" name="admin_email" id="admin_email" required value="<?php echo rishe_e($v['admin_email']); ?>"></label>
				</div>
				<label class="rishe-field"><span>رمز عبور</span><input class="rishe-input ltr" type="password" name="admin_pass" id="admin_pass" required minlength="8"><small>حداقل ۸ کاراکتر</small></label>
				<input type="hidden" name="sample" value="0">
				<label class="rishe-check"><input type="checkbox" name="sample" id="sample" value="1" <?php echo $v['sample'] === '1' ? 'checked' : ''; ?>>یک دوره‌ی نمونه هم بساز (برای تست اپ)</label>
				<button class="rishe-btn is-primary is-block" type="submit">نصب</button>
			</form>
		<?php endif; ?>
	</div>
</body>
</html>
